# if - else statement 
num1 = 100

if num1 > 50 :
    print ("True")
else :
    print ("False")


# short hand if - else
num2 = 200

res = "true" if num2 >= 100 else "false"
print(res);

# elif statement :
# elif statement stands for else if, It allows us to check multiple conditions , providing a way to execute
# different blocks of code based on which condition is true. 

age = 12

if age <= 12 :
    print("child")
elif age < 18 :
    print("Teenager")
else :
    print("Adult")



