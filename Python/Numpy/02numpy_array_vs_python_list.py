# Python provides lists by default, not numerical arrays.

# Lists are general-purpose and can store mixed data types.

# Python has an array module, but it is limited and rarely used.

# NumPy provides efficient numerical arrays (ndarray).
# NumPy arrays are fast, memory-efficient, and optimized for math operations.
# NumPy arrays store only one data type, similar to C/C++ arrays.

# Lists are used for general programming and logic.

# NumPy arrays are mainly used for data analysis and machine learning.
# NumPy arrays must be imported from the NumPy library.

# When people say "Python array", they usually mean a NumPy array.

