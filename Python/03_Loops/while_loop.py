# while loop 

num = 0

while (num < 3):
    num += 1
    print("Number : ", num)


# while loop with break and continue :

count = 0

while (count < 5):
    count += 1
    if (count == 3):
        continue
    print(count)


count2 = 0

while (count2 < 5):

    if (count == 3):
        break
    print(count2)
    count2 += 1

    
# Infinite while loop 

while True :
    print("xyz")



